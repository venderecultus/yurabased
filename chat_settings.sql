create table if not exists public.chat_settings (
  chat_id text primary key,
  aggression integer not null default 60 check (aggression in (0, 30, 60, 100)),
  profanity boolean not null default true,
  stickers boolean not null default true
);

alter table public.messages
  add column if not exists telegram_message_id bigint;

create table if not exists public.chat_topics (
  chat_id text not null,
  thread_id bigint not null,
  name text not null,
  blocked boolean not null default false,
  primary key (chat_id, thread_id)
);

-- Run once in Supabase SQL Editor before deploying the updated bot.

create table if not exists public.publishing_channels (
  channel_id text primary key,
  title text not null,
  enabled boolean not null default true
);

create table if not exists public.publishing_settings (
  channel_id text primary key references public.publishing_channels(channel_id) on delete cascade,
  mode text not null default 'manual' check (mode in ('manual', 'automatic')),
  interval_minutes integer not null default 1440 check (interval_minutes > 0),
  probability integer not null default 100 check (probability between 0 and 100),
  source_channel_id text,
  last_attempt_at timestamptz
);

create table if not exists public.publishing_templates (
  id bigint generated by default as identity primary key,
  channel_id text not null references public.publishing_channels(channel_id) on delete cascade,
  name text not null,
  prompt text not null,
  enabled boolean not null default true,
  unique(channel_id, name)
);

create table if not exists public.publishing_source_posts (
  id bigint generated by default as identity primary key,
  channel_id text not null,
  message_id bigint not null,
  photo_file_id text,
  caption text not null default '',
  created_at timestamptz not null default now(),
  unique(channel_id, message_id)
);

create table if not exists public.publishing_candidates (
  id bigint generated by default as identity primary key,
  channel_id text not null references public.publishing_channels(channel_id) on delete cascade,
  photo_file_id text,
  caption text not null,
  status text not null default 'pending' check (status in ('pending', 'published', 'cancelled')),
  created_at timestamptz not null default now()
);
